    <h1>Política de Privacidade</h1>
    <p class="updated">Última atualização: 16 de setembro de 2026</p>

    <p>Esta política explica como a Contacto Digital trata dados pessoais no portal e na aplicação Contacto Digital Dash, utilizada pelos seus clientes para consultar informação operacional dos respetivos eventos.</p>

    <h2>1. Responsável pelo tratamento</h2>
    <p>A Contacto Digital é responsável pelo tratamento dos dados necessários ao acesso e funcionamento da aplicação. Pode contactar-nos através de <a href="mailto:info@contactodigital.pt">info@contactodigital.pt</a>, do telefone <a href="tel:+351910918377">+351 910 918 377</a> ou na Rua de São Gonçalo 49, 4460-472 Senhora da Hora, Matosinhos, Portugal.</p>

    <h2>2. Dados tratados</h2>
    <ul>
        <li>Dados de conta e autenticação, como nome, endereço de email e credenciais protegidas.</li>
        <li>Tokens de sessão guardados de forma segura no dispositivo para manter a autenticação.</li>
        <li>Dados técnicos de segurança e diagnóstico, como endereço IP, data e hora dos acessos e informação técnica enviada pelo dispositivo ou navegador.</li>
        <li>Informação operacional e agregada dos eventos a que a organização do utilizador concedeu acesso.</li>
    </ul>

    <h2>3. Finalidades e fundamento</h2>
    <p>Tratamos estes dados para autenticar utilizadores, disponibilizar o serviço contratado, apresentar relatórios do evento, prestar suporte, prevenir acessos indevidos e manter a segurança e fiabilidade da plataforma. O tratamento baseia-se na execução do serviço contratado e nos nossos interesses legítimos de operação e segurança.</p>

    <h2>4. Partilha, publicidade e rastreamento</h2>
    <p>Não vendemos dados pessoais, não apresentamos publicidade e não usamos os dados para rastrear utilizadores entre aplicações ou websites de outras empresas. Podemos recorrer a fornecedores de alojamento, infraestrutura e suporte que tratam dados apenas para prestar estes serviços e sob obrigações adequadas de confidencialidade e segurança. A abertura de serviços externos, como o WhatsApp, fica sujeita às políticas desses serviços.</p>

    <h2>5. Conservação e segurança</h2>
    <p>Conservamos os dados durante o período necessário à prestação do serviço, ao cumprimento de obrigações legais e à proteção de direitos. As credenciais não são guardadas em texto simples. Aplicamos controlos técnicos e organizativos destinados a proteger a informação contra acesso, alteração, divulgação ou perda indevidos.</p>

    <h2>6. Direitos dos titulares</h2>
    <p>Nos termos aplicáveis, pode solicitar acesso, retificação, apagamento, limitação ou portabilidade dos seus dados, bem como opor-se a determinados tratamentos. As contas da aplicação são atribuídas pela organização cliente; a correção ou eliminação da conta pode ser pedida ao administrador dessa organização ou diretamente à Contacto Digital através dos contactos acima.</p>

    <h2>7. Transferências e menores</h2>
    <p>Quando um fornecedor trata dados fora do Espaço Económico Europeu, usamos mecanismos de transferência legalmente reconhecidos. A aplicação destina-se a utilizadores profissionais autorizados e não é dirigida a crianças.</p>

    <h2>8. Alterações</h2>
    <p>Podemos atualizar esta política quando o serviço ou os requisitos legais mudarem. A data da revisão mais recente é indicada no início desta página.</p>

